import os
import re
import threading

import pandas as pd
from lxml import etree
from pptx import Presentation
from pptx.enum.shapes import PP_PLACEHOLDER
from pptx.text.fonts import FontFiles
from pptx.util import Pt


MAX_ATTRIBUTIONS_PER_SLIDE = 4
MAX_FONT_SIZE = 18
MIN_FONT_SIZE = 14

# Template slide numbers are 1-based.
EXCLUDED_SAMPLE_SLIDE_NUMBER = 2
PERMISSION_SAMPLE_SLIDE_NUMBER = 3
END_SLATE_TEMPLATE_SLIDE_NUMBER = 4

# If slide 5 is present, use it as the aigen sample.
# Otherwise, aigen uses the excluded layout.
AIGEN_SAMPLE_SLIDE_NUMBER = 5

DRAWINGML_NS = "http://schemas.openxmlformats.org/drawingml/2006/main"

# python-pptx maintains a process-wide font cache. This lock prevents
# simultaneous requests from updating or scanning that cache at once.
_FONT_LOCK = threading.RLock()

# Keep the original method before configuring Linux font search paths.
_ORIGINAL_FONT_DIRECTORIES = FontFiles._font_directories


def configure_font_search(font_dir=None):
    """Include system font folders and the uploaded font folder in font search."""
    try:
        directories = list(_ORIGINAL_FONT_DIRECTORIES())
    except (OSError, AttributeError, TypeError):
        directories = []

    directories.extend([
        "/usr/share/fonts",
        "/usr/local/share/fonts",
        os.path.expanduser("~/.local/share/fonts"),
        os.path.expanduser("~/.fonts"),
    ])

    if font_dir:
        directories.insert(0, os.path.abspath(font_dir))

    unique_directories = []
    seen = set()

    for directory in directories:
        if not directory:
            continue

        directory = os.path.abspath(directory)

        if directory not in seen and os.path.isdir(directory):
            unique_directories.append(directory)
            seen.add(directory)

    # Override python-pptx's font-directory lookup for this process.
    FontFiles._font_directories = classmethod(
        lambda cls: list(unique_directories)
    )

    # Force a rescan so python-pptx can find the uploaded fonts.
    FontFiles._font_files = None


def get_template_font_style(prs, sample_slide):
    """Get BODY font family and styling from a sample slide."""
    body_shape = None

    # Prefer BODY placeholder index 2, matching the original script.
    for shape in sample_slide.placeholders:
        if (
            shape.placeholder_format.type == PP_PLACEHOLDER.BODY
            and shape.placeholder_format.idx == 2
        ):
            body_shape = shape
            break

    # Otherwise use the first BODY placeholder.
    if body_shape is None:
        for shape in sample_slide.placeholders:
            if shape.placeholder_format.type == PP_PLACEHOLDER.BODY:
                body_shape = shape
                break

    font_family = None
    bold = None
    italic = None

    if body_shape is not None:
        for paragraph in body_shape.text_frame.paragraphs:
            for run in paragraph.runs:
                if font_family is None and run.font.name:
                    font_family = run.font.name

                if bold is None:
                    bold = run.font.bold

                if italic is None:
                    italic = run.font.italic

                if font_family is not None:
                    break

            if font_family is not None:
                break

    # If the sample placeholder inherits its font, look for the theme body font.
    if font_family is None and prs.slide_masters:
        for rel in prs.slide_masters[0].part.rels.values():
            if rel.reltype.endswith("/theme"):
                theme_root = etree.fromstring(rel.target_part.blob)
                latin_font = theme_root.find(
                    f".//{{{DRAWINGML_NS}}}fontScheme/"
                    f"{{{DRAWINGML_NS}}}minorFont/"
                    f"{{{DRAWINGML_NS}}}latin"
                )

                if latin_font is not None:
                    font_family = latin_font.get("typeface")
                    if font_family:
                        break

    if not font_family:
        raise ValueError(
            "Could not determine the BODY font from the template. "
            "Check the sample slide's BODY placeholder and theme font."
        )

    return {
        "font_family": font_family,
        "bold": bold,
        "italic": italic,
    }


def get_body_shape(slide):
    """Find the preferred BODY placeholder on a generated slide."""
    for shape in slide.placeholders:
        if (
            shape.placeholder_format.type == PP_PLACEHOLDER.BODY
            and shape.placeholder_format.idx == 2
        ):
            return shape

    for shape in slide.placeholders:
        if shape.placeholder_format.type == PP_PLACEHOLDER.BODY:
            return shape

    return None


def add_fallback_textbox(slide, prs):
    """Add a textbox if the selected layout has no BODY placeholder."""
    left = prs.slide_width // 4
    top = prs.slide_height // 4
    width = prs.slide_width // 2
    height = prs.slide_height // 2

    return slide.shapes.add_textbox(left, top, width, height)


def set_fitted_text(shape, text, font_style):
    """
    Fit text at up to 18 pt using the template's font.

    Returns the font size selected by python-pptx. The caller checks whether
    it is at least 14 pt.
    """
    text_frame = shape.text_frame
    text_frame.text = text
    text_frame.word_wrap = True

    if not text.strip():
        return MAX_FONT_SIZE

    try:
        text_frame.fit_text(
            font_family=font_style["font_family"],
            max_size=MAX_FONT_SIZE,
            bold=bool(font_style["bold"]),
            italic=bool(font_style["italic"]),
        )
    except (KeyError, OSError) as exc:
        raise RuntimeError(
            f"Could not find or measure the template font "
            f"{font_style['font_family']!r}. Upload the matching font files, "
            "including the required weight or style."
        ) from exc

    fitted_sizes = [
        run.font.size.pt
        for paragraph in text_frame.paragraphs
        for run in paragraph.runs
        if run.font.size is not None
    ]

    fitted_size = min(fitted_sizes, default=MAX_FONT_SIZE)

    # Keep the template font and styling while applying the fitted size.
    for paragraph in text_frame.paragraphs:
        for run in paragraph.runs:
            run.font.name = font_style["font_family"]
            run.font.size = Pt(fitted_size)

            if font_style["bold"] is not None:
                run.font.bold = font_style["bold"]

            if font_style["italic"] is not None:
                run.font.italic = font_style["italic"]

    return fitted_size


def get_attribution_text(row):
    """Return a clean attribution string from a dataframe row."""
    value = getattr(row, "attribution_text", "")

    if pd.isna(value):
        return ""

    return str(value).strip()


def required_text(value, column_name):
    """Return a non-empty string value or raise an informative error."""
    if pd.isna(value):
        raise ValueError(f"The CSV has a blank value in {column_name!r}.")

    text = str(value).strip()

    if not text:
        raise ValueError(f"The CSV has a blank value in {column_name!r}.")

    return text


def filename_component(value):
    """Sanitize one filename component while preserving letters, digits, _ and -."""
    text = str(value).strip()
    cleaned = []

    for character in text:
        if character.isalnum() or character in {"_", "-"}:
            cleaned.append(character)
        elif character.isspace():
            cleaned.append("-")

    result = "".join(cleaned).strip("-_")
    return result or "unknown"


def text_before_space_dash(value, column_name):
    """
    Return the part before the first space followed by a dash.

    Examples:
        'Selin - Introduction' -> 'Selin'
        'S1 - Introduction'    -> 'S1'
    """
    text = required_text(value, column_name)
    prefix = re.split(r"\s+-", text, maxsplit=1)[0].strip()

    if not prefix:
        raise ValueError(
            f"Could not derive the filename part from {column_name!r}: "
            f"{text!r}"
        )

    return prefix


def make_output_filename(course_number, video_edit_id, lecture_name, resource_name):
    """
    Build a filename like UCE_0004_Selin_S1.pptx.
    """
    course_text = required_text(course_number, "course_number")
    program = course_text.split(".", 1)[0].strip()

    video_id = required_text(video_edit_id, "video_edit_id")
    last_name = text_before_space_dash(lecture_name, "lecture_name")
    segment = text_before_space_dash(resource_name, "resource_name")

    parts = [
        filename_component(program),
        filename_component(video_id),
        filename_component(last_name),
        filename_component(segment),
    ]

    return "_".join(parts) + "_slates.pptx"


def retain_generated_slides_and_end_slate(
    prs,
    original_slide_ids,
    end_slate_id,
):
    """Keep generated slides and the original end slate; move end slate last."""
    slide_id_list = prs.slides._sldIdLst
    original_ids = {slide_id.id for slide_id in original_slide_ids}

    generated_slide_ids = [
        slide_id
        for slide_id in list(slide_id_list)
        if slide_id.id not in original_ids
    ]

    keep_ids = {slide_id.id for slide_id in generated_slide_ids}
    keep_ids.add(end_slate_id.id)

    # Remove original template slides except the end slate.
    for slide_id in list(slide_id_list):
        if slide_id.id not in keep_ids:
            relationship_id = slide_id.rId
            slide_id_list.remove(slide_id)
            prs.part.drop_rel(relationship_id)

    # Put the retained end slate after all generated slides.
    slide_id_list.remove(end_slate_id)
    slide_id_list.append(end_slate_id)


def _create_ppt_from_dataframe(df, template_path, output_dir):
    os.makedirs(output_dir, exist_ok=True)

    required_columns = {
        "resource_name",
        "attribution_type",
        "attribution_text",
        "video_edit_id",
        "course_number",
        "lecture_name",
    }
    missing_columns = required_columns.difference(df.columns)

    if missing_columns:
        raise ValueError(
            "The CSV is missing required column(s): "
            + ", ".join(sorted(missing_columns))
        )

    order = ["excluded", "permission", "aigen"]
    df = df.copy()
    df["attribution_type"] = pd.Categorical(
        df["attribution_type"],
        categories=order,
        ordered=True,
    )

    # One deck per video segment. Group on all fields used to identify/name it.
    group_columns = [
        "course_number",
        "video_edit_id",
        "lecture_name",
        "resource_name",
    ]

    for group_values, resource_group in df.groupby(
        group_columns,
        dropna=False,
        sort=False,
        observed=True,
    ):
        (
            course_number,
            video_edit_id,
            lecture_name,
            resource_name,
        ) = group_values

        prs = Presentation(template_path)
        template_slide_count = len(prs.slides)

        required_slide_numbers = [
            EXCLUDED_SAMPLE_SLIDE_NUMBER,
            PERMISSION_SAMPLE_SLIDE_NUMBER,
            END_SLATE_TEMPLATE_SLIDE_NUMBER,
        ]

        if template_slide_count < max(required_slide_numbers):
            raise ValueError(
                f"The template has {template_slide_count} slides, but at "
                f"least {max(required_slide_numbers)} are required for the "
                "excluded sample, permission sample, and end slate."
            )

        # Capture original template slide IDs before adding generated slides.
        original_slide_ids = list(prs.slides._sldIdLst)

        # Slide 4 is retained as the end slate and moved to the final position.
        end_slate_id = original_slide_ids[
            END_SLATE_TEMPLATE_SLIDE_NUMBER - 1
        ]

        excluded_sample_slide = prs.slides[
            EXCLUDED_SAMPLE_SLIDE_NUMBER - 1
        ]
        permission_sample_slide = prs.slides[
            PERMISSION_SAMPLE_SLIDE_NUMBER - 1
        ]

        reference_layout_map = {
            "excluded": excluded_sample_slide.slide_layout,
            "permission": permission_sample_slide.slide_layout,
        }

        font_style_map = {
            "excluded": get_template_font_style(
                prs,
                excluded_sample_slide,
            ),
            "permission": get_template_font_style(
                prs,
                permission_sample_slide,
            ),
        }

        # Use slide 5 as aigen's sample if it exists; otherwise use excluded.
        if (
            AIGEN_SAMPLE_SLIDE_NUMBER is not None
            and template_slide_count >= AIGEN_SAMPLE_SLIDE_NUMBER
        ):
            aigen_sample_slide = prs.slides[
                AIGEN_SAMPLE_SLIDE_NUMBER - 1
            ]
            reference_layout_map["aigen"] = aigen_sample_slide.slide_layout
            font_style_map["aigen"] = get_template_font_style(
                prs,
                aigen_sample_slide,
            )
        else:
            reference_layout_map["aigen"] = reference_layout_map["excluded"]
            font_style_map["aigen"] = font_style_map["excluded"]

        for attribution_type, type_group in resource_group.groupby(
            "attribution_type",
            observed=True,
        ):
            # Keep the original fallback behavior for unrecognized categories.
            slide_layout = reference_layout_map.get(
                attribution_type,
                reference_layout_map["excluded"],
            )
            font_style = font_style_map.get(
                attribution_type,
                font_style_map["excluded"],
            )

            rows = list(type_group.itertuples(index=False))
            row_index = 0

            while row_index < len(rows):
                remaining = len(rows) - row_index
                batch_size = min(MAX_ATTRIBUTIONS_PER_SLIDE, remaining)

                # Add one slide. If the batch does not fit at 14 pt or larger,
                # reduce the batch on this same slide. Remaining entries are
                # added to subsequent slides.
                new_slide = prs.slides.add_slide(slide_layout)
                body_shape = get_body_shape(new_slide)

                if body_shape is None:
                    body_shape = add_fallback_textbox(new_slide, prs)

                slide_fits = False

                while batch_size >= 1:
                    batch = rows[row_index:row_index + batch_size]
                    body_text = "\n".join(
                        get_attribution_text(row)
                        for row in batch
                    )

                    fitted_size = set_fitted_text(
                        body_shape,
                        body_text,
                        font_style,
                    )

                    if fitted_size >= MIN_FONT_SIZE:
                        row_index += batch_size
                        slide_fits = True
                        break

                    batch_size -= 1

                if not slide_fits:
                    attribution_text = get_attribution_text(rows[row_index])
                    raise ValueError(
                        f"An individual attribution cannot fit at "
                        f"{MIN_FONT_SIZE} pt. Resource: {resource_name!r}; "
                        f"type: {attribution_type!r}; "
                        f"text: {attribution_text!r}. Shorten the text or "
                        "enlarge the placeholder in the template."
                    )

        retain_generated_slides_and_end_slate(
            prs,
            original_slide_ids,
            end_slate_id,
        )

        output_filename = make_output_filename(
            course_number=course_number,
            video_edit_id=video_edit_id,
            lecture_name=lecture_name,
            resource_name=resource_name,
        )
        output_path = os.path.join(output_dir, output_filename)

        prs.save(output_path)
        print(f"✅ Presentation saved: {output_path}")


def create_ppt_from_dataframe(
    df,
    template_path,
    output_dir,
    font_dir=None,
):
    """
    Generate one presentation per video segment.

    font_dir should contain the font files uploaded with the web-app request.
    """
    with _FONT_LOCK:
        configure_font_search(font_dir)
        _create_ppt_from_dataframe(df, template_path, output_dir)


def main():
    csv_path = input("Enter path to CSV file: ")
    template_path = input("Enter template path: ")
    output_dir = input("Enter output directory: ")
    font_dir = input("Enter folder containing font files: ")

    # Read identifier columns as strings so values like "0004" retain zeros.
    df = pd.read_csv(
        csv_path,
        dtype={
            "video_edit_id": "string",
            "course_number": "string",
            "lecture_name": "string",
            "resource_name": "string",
        },
    )

    create_ppt_from_dataframe(
        df=df,
        template_path=template_path,
        output_dir=output_dir,
        font_dir=font_dir,
    )


if __name__ == "__main__":
    main()
